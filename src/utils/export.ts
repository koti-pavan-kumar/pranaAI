function generateRecommendations(journal: Array<{ mood: string }>, breathing: Array<{ duration: number }>): string {
  const recommendations: string[] = [];

  // Analyze mood patterns
  const moodCounts: Record<string, number> = {};
  journal.forEach((e: { mood: string }) => {
    moodCounts[e.mood] = (moodCounts[e.mood] || 0) + 1;
  });

  const dominantMood = Object.entries(moodCounts).sort((a, b) => b[1] - a[1])[0];

  if (dominantMood) {
    if (dominantMood[0] === 'anxious' || dominantMood[0] === 'stressed') {
      recommendations.push('• Try the 4-7-8 breathing pattern to reduce anxiety');
      recommendations.push('• Practice box breathing (4-4-4-4) for focus');
    } else if (dominantMood[0] === 'sad' || dominantMood[0] === 'depressed') {
      recommendations.push('• Consider talking to someone you trust');
      recommendations.push('• Try energizing breathing patterns');
    } else if (dominantMood[0] === 'happy' || dominantMood[0] === 'calm') {
      recommendations.push('• Great mood streak! Keep up the breathing practice');
    }
  }

  // Analyze breathing consistency
  if (breathing.length < 5) {
    recommendations.push('• Aim for at least 5 breathing sessions per week');
  }

  if (breathing.some((s: { duration: number }) => s.duration < 60)) {
    recommendations.push('• Try extending sessions to 2-3 minutes for deeper benefits');
  }

  if (recommendations.length === 0) {
    recommendations.push('• Keep journaling and breathing regularly!');
    recommendations.push('• Your data shows a balanced wellness routine');
  }

  return recommendations.join('\n');
}

/**
 * Share report via Web Share API (mobile)
 */
export async function shareReport(userId: string): Promise<void> {
  const summary = await generateTextSummary(userId);

  if (navigator.share) {
    try {
      await navigator.share({
        title: 'PranaAI Wellness Report',
        text: summary,
      });
      console.log('[Export] Report shared via Web Share API');
    } catch (err) {
      console.log('[Export] Share cancelled or failed:', err);
    }
  } else {
    // Fallback: copy to clipboard
    await navigator.clipboard.writeText(summary);
    console.log('[Export] Report copied to clipboard');
  }
}
