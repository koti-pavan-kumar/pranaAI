/**
 * Export Utilities — Office Kit Integration
 * Generate wellness reports for export
 */

import { exportUserData } from '../lib/db';

/**
 * Export user data as JSON file
 */
export async function exportAsJSON(userId: string): Promise<void> {
  const data = await exportUserData(userId);
  const blob = new Blob([data], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `pranaai-wellness-report-${new Date().toISOString().split('T')[0]}.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
  console.log('[Export] JSON report downloaded');
}

/**
 * Export user data as CSV file
 */
export async function exportAsCSV(userId: string): Promise<void> {
  const data = JSON.parse(await exportUserData(userId));

  // Journal CSV
  const journalHeaders = ['Date', 'Mood', 'Text', 'Sentiment Score', 'Tags'];
  const journalRows = data.journal.map((e: { timestamp: number; mood: string; text: string; sentimentScore: number; tags: string[] }) => [
    new Date(e.timestamp).toISOString(),
    e.mood,
    `"${e.text.replace(/"/g, '""')}"`,
    e.sentimentScore.toFixed(2),
    e.tags.join('; '),
  ]);

  const journalCSV = [journalHeaders.join(','), ...journalRows.map((r: string[]) => r.join(','))].join('\n');

  // Breathing CSV
  const breathingHeaders = ['Date', 'Pattern', 'Duration (sec)', 'Cycles'];
  const breathingRows = data.breathing.map((s: { timestamp: number; pattern: { name: string }; duration: number; completedCycles: number }) => [
    new Date(s.timestamp).toISOString(),
    s.pattern.name,
    s.duration,
    s.completedCycles,
  ]);

  const breathingCSV = [breathingHeaders.join(','), ...breathingRows.map((r: string[]) => r.join(','))].join('\n');

  // Combine
  const combined = `JOURNAL ENTRIES\n${journalCSV}\n\nBREATHING SESSIONS\n${breathingCSV}`;

  const blob = new Blob([combined], { type: 'text/csv' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `pranaai-wellness-data-${new Date().toISOString().split('T')[0]}.csv`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
  console.log('[Export] CSV report downloaded');
}

